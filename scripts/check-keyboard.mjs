import assert from 'node:assert/strict'
import { chromium, firefox, webkit, expect } from '@playwright/test'

// Run against `npm run build && npm run preview -- --host 127.0.0.1`.
const browser = await ({ chromium, firefox, webkit }[process.argv[2] ?? 'chromium']).launch()
const page = await browser.newPage({ viewport: { width: 1280, height: 600 } })
const errors = []
page.on('pageerror', (error) => errors.push(error.message))
page.on('console', (message) => {
  if (['error', 'warning'].includes(message.type())) errors.push(message.text())
})
// macOS WebKit follows Safari's Option+Tab setting for all controls.
const press = (key) => page.keyboard.press(process.argv[2] === 'webkit' && key.endsWith('Tab') ? `Alt+${key}` : key)
const focused = page.locator(':focus')

try {
  await page.goto('http://127.0.0.1:5173')
  await expect(page.locator('.mode-card')).toHaveCount(3)
  await expect(page.locator('#root')).not.toHaveClass(/keyboard-navigation/)
  await press('Tab')
  await expect(focused).toContainText('Single player')
  await press('ArrowRight')
  await expect(focused).toContainText('Local multiplayer')
  await press('Enter')
  await expect(focused).toContainText('Random fighter')
  await press('Tab')
  await expect(focused).toHaveAttribute('type', 'search')
  await page.keyboard.type('tigr')
  await press('ArrowLeft')
  assert.equal(await focused.evaluate((input) => input.selectionStart), 3)
  await press('Tab')
  await expect(focused).toContainText('Tiger')
  await press('Enter')
  await expect(focused).toHaveAttribute('aria-pressed', 'true')
  await press('Tab')
  await expect(focused).toContainText('Random fighter')
  await press('Tab')
  await page.keyboard.type('gorila')
  await press('Tab')
  await expect(focused).toContainText('Gorilla')
  await press(' ')
  await expect(focused).toHaveAttribute('aria-pressed', 'true')
  await expect(page.getByRole('button', { name: 'Start showdown' })).toBeEnabled()
  await press('Tab')
  await expect(focused).toHaveText('Back')
  await press('Shift+Tab')
  await expect(focused).toContainText('Gorilla')
  await press('Tab')
  await press('Tab')
  await expect(focused).toHaveText('Start showdown')
  await expect(focused).toBeEnabled()
  await press('Enter')
  await expect(focused).toHaveClass(/move-card/)
  await press('ArrowRight')
  await expect(focused.locator('.move-key')).toHaveText('2')
  await press('ArrowDown')
  await expect(focused.locator('.move-key')).toHaveText('4')
  await press('Enter')
  await expect(page.locator('.faceoff-arena')).toHaveAttribute('data-animation', 'guard')
  await expect(page.locator('.move-card:enabled').first()).toBeVisible()
  await expect(focused).toHaveClass(/move-card/)

  for (const key of ['1', '2', '3', '4']) {
    const move = page.locator('.move-card').nth(Number(key) - 1)
    const before = await page.locator('.battle-message').textContent()
    const disabled = await move.isDisabled()
    await press(key)
    if (disabled) await expect(page.locator('.battle-message')).toHaveText(before)
    else await expect(page.locator('.faceoff-arena')).toHaveAttribute('data-animation', /.+/)
    await expect(page.locator('.move-card:enabled').first()).toBeVisible()
  }
  const before = await page.locator('.battle-message').textContent()
  await press('Control+1')
  await expect(page.locator('.battle-message')).toHaveText(before)
  await page.keyboard.down('1')
  await expect(page.locator('.move-card:enabled').first()).toBeVisible()
  const after = await page.locator('.battle-message').textContent()
  await page.keyboard.down('1') // Holding a shortcut must not take another turn.
  await expect(page.locator('.battle-message')).toHaveText(after)
  await page.keyboard.up('1')

  for (let turn = 0; turn < 100 && await page.locator('.move-grid').count(); turn += 1) {
    await expect(page.locator('.move-card:enabled, .battle-result-panel').first()).toBeVisible()
    await press('3')
  }
  await expect(focused).toHaveText('Rematch')
  await press('Enter')
  await expect(focused).toHaveClass(/move-card/)
  await press('Shift+Tab')
  await expect(focused).toHaveText('Change fighters')
  await press('Enter')
  await expect(focused).toContainText('Random fighter')
  await press('Tab')
  const rosterSize = await page.locator('.roster').first().locator('button').count()
  await page.keyboard.type('zzzzzz')
  await press('1')
  await expect(focused).toHaveValue('zzzzzz1')
  await expect(page.locator('.roster-empty')).toBeVisible()
  await press('Tab')
  await expect(focused).toContainText('Random fighter')
  await press('Shift+Tab')
  await expect(focused).toHaveAttribute('type', 'search')
  await press('ControlOrMeta+A')
  await press('Backspace')
  await expect(page.locator('.roster').first().locator('button')).toHaveCount(rosterSize)
  await press('Tab')
  await expect(focused).toHaveClass(/animal-card/)
  await expect(focused).toContainText('Tiger')
  await press('ArrowDown')
  await expect(focused).toContainText('Hippo')
  await press('ArrowUp')
  await expect(focused).toContainText('Tiger')
  for (let row = 0; row < 8; row += 1) await press('ArrowDown')
  assert.ok(await page.locator('.roster').first().evaluate((roster) => roster.scrollTop) > 0)
  await press('Tab') // One roster Tab stop even after browsing without selecting.
  await expect(focused).toContainText('Random fighter')
  await page.locator('.animal-card').first().click()
  await expect(page.locator('#root')).not.toHaveClass(/keyboard-navigation/)
  await page.getByRole('button', { name: 'Back', exact: true }).click()
  await expect(page.locator('#root')).not.toHaveClass(/keyboard-navigation/)
  await expect(page.locator('.mode-screen')).toBeVisible()
  assert.deepEqual(errors, [])
  console.log(`${process.argv[2] ?? 'chromium'} ${browser.version()}: keyboard selection, grids, search editing, turn recovery, 1–4, disabled/repeated/modified shortcuts, result, rematch, back and mouse handoff passed; console clean.`)
} finally {
  await browser.close()
}
